// README.md is generated from the state; this is its template.

import { designFor } from './cars.mjs';
import { COOLDOWN_HOURS, OWNER_DAILY_CAP, REPO, VISITOR_DROPS } from './farm.mjs';
import { STAGES, stageOf } from './plant.mjs';
import { daysBetween } from './util.mjs';

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const date = (iso) => {
  const d = new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso);
  return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
};
const user = (login) => `[@${login}](https://github.com/${login})`;
const num = (v) => v.toLocaleString('en-US');

export const WATER_TITLE = '💧 Water the car';

export function waterUrl() {
  const body = [
    `👋 Thanks for helping! Just hit **Create**. The garden bot adds 💧 ${VISITOR_DROPS} drops, redraws the garden and closes this issue in about a minute.`,
    '',
    '_Keep the title as it is. You can water once a day._',
  ].join('\n');
  return `https://github.com/${REPO}/issues/new?title=${encodeURIComponent(WATER_TITLE)}&body=${encodeURIComponent(body)}`;
}

function logLine(e) {
  switch (e.kind) {
    case 'visitor':
      return `💧 ${user(e.who)} gave ${e.drops} drops · ${date(e.at)}`;
    case 'commits':
      return e.drops > 0
        ? `⌨️ My ${num(e.contributions)} contribution${e.contributions === 1 ? '' : 's'} on ${date(e.date)} gave ${e.drops} drop${e.drops === 1 ? '' : 's'}`
        : `⌨️ My ${num(e.contributions)} contribution${e.contributions === 1 ? '' : 's'} on ${date(e.date)} didn't count: it was already ripe, waiting for you`;
    case 'harvest':
      return `🎉 Crop #${e.crop} harvested by ${user(e.who)}: a ${e.name} · ${date(e.at)}`;
    case 'sprouted':
      return `🌱 It sprouted · ${date(e.at)}`;
    default:
      return null;
  }
}

export function renderReadme(state, { stl, now = new Date(), files }) {
  const { crop } = state;
  const g = Math.min(1, crop.water / crop.goal);
  const stage = stageOf(g);
  const design = designFor(crop.number);
  const url = waterUrl();
  const ripe = crop.water >= crop.goal - 1;
  const days = daysBetween(state.plantedOn, now);
  const sprouted = state.log.find((e) => e.kind === 'sprouted') ?? state.log[state.log.length - 1];
  const sproutDays = sprouted ? daysBetween(state.plantedOn, new Date(sprouted.at)) : days;

  const gardeners = Object.entries(state.gardeners)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 30);
  const avatars = gardeners
    .map(([login, drops]) => `<a href="https://github.com/${login}"><img src="https://github.com/${login}.png?size=80" width="40" height="40" alt="@${login}" title="@${login} · ${drops} drops"></a>`)
    .join(' ');
  const lines = state.log.map(logLine).filter(Boolean).slice(0, 8);

  const status = ripe
    ? `**Crop #${crop.number} is ripe. One more drop and that ${design.name} is yours.**`
    : `**Crop #${crop.number} · ${STAGES[stage]} · 💧 ${crop.water} / ${crop.goal} drops**`;

  return `<!-- Generated by scripts/garden.mjs from garden/state.json. Edit those, not this file. -->

<div align="center">

<a href="${url}">
<picture>
  <source media="(prefers-color-scheme: dark)" srcset="${files.sceneNight}">
  <img alt="A car growing out of the ground like a plant, in front of a pink wall. Crop #${crop.number}: ${STAGES[stage].toLowerCase()}, ${crop.water} of ${crop.goal} drops." src="${files.sceneDay}" width="100%">
</picture>
</a>

<a href="${url}"><img alt="Water the car" src="${files.button}" height="64"></a>

${status}<br>
<sub>I planted a toy car on ${date(state.plantedOn)} and told you to just wait. It sprouted ${num(sproutDays)} days later.<br>
My commits water it every day. You can too: one click, ${VISITOR_DROPS} drops, once a day.<br>
Whoever gives the last drop gets the car, with their name on the plate.</sub>

</div>

### 🧑‍🌾 Gardeners

${avatars || '_Nobody yet. The first drop could be yours._'}

<sub>⌨️ Me, mostly through commits: ${num(state.ownerDrops)} drops so far.</sub>

${lines.length ? `<details>\n<summary>Latest drops</summary>\n\n${lines.map((l) => `- ${l}`).join('\n')}\n\n</details>` : ''}

### 🏁 The garage

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="${files.garageNight}">
  <img alt="${state.harvests.length ? `${state.harvests.length} harvested cars` : 'The garage, still empty'}" src="${files.garageDay}" width="100%">
</picture>

### 🧊 Spoiler

<sub>This is what crop #${crop.number} grows into: a ${design.name}. Drag to spin it.</sub>

\`\`\`stl
${stl.trimEnd()}
\`\`\`

<details>
<summary>📼 Previously on this profile</summary>
<br>

**2023.** You got rick rolled. [Watch it again](rolled.gif).

**2024.** I planted a toy car and told you to just wait.

<img alt="Just wait." src="just-wait.gif" width="400">

**2026.** It sprouted. Day ${num(days)} and counting.

</details>

<details>
<summary>🛠️ How does a README grow a car?</summary>
<br>

- No servers. The garden is a handful of animated SVGs, redrawn by GitHub Actions whenever something changes.
- The 💧 button opens a pre-filled issue. A workflow reads it, adds ${VISITOR_DROPS} drops (once per person every ${COOLDOWN_HOURS} hours), redraws the garden, replies and closes the issue.
- Every morning another workflow counts my contributions from the day before: 1 drop each, up to ${OWNER_DAILY_CAP} a day. They never give the last drop. That one is reserved for a visitor.
- Whoever gives the last drop gets the car: it's parked in the garage with their name on the plate, and a new seed goes in. Every crop grows a different car.
- The 3D model is ASCII STL built from the same outline as the drawing. GitHub renders \`stl\` code blocks with its built-in 3D viewer.
- Plain Node.js, no dependencies: [\`scripts/\`](scripts), state in [\`garden/state.json\`](garden/state.json).

</details>
`;
}
